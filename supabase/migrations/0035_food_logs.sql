-- 食材數值：衛生福利部食品藥物管理署「食品營養成分資料集」（data.gov.tw/dataset/8543，2026-10-05 版）每 100 克含量。
-- 「份量克數」（1 碗＝幾克等）為家用份量估計，待 James 確認，見 docs/food_reference_review.md。
-- 外食品項由管理員在後台新增（is_custom），數值與來源由 James 提供。

-- ── 食物清單 ─────────────────────────────────────────────────────────────
create table public.foods (
  id             uuid primary key default gen_random_uuid(),
  name           text not null check (char_length(name) between 1 and 40),
  category       text not null check (char_length(category) between 1 and 20),
  portion_label  text not null check (char_length(portion_label) between 1 and 30),
  portion_g      numeric(6,1) check (portion_g > 0),
  kcal_100g      numeric(6,1) check (kcal_100g >= 0),
  protein_100g   numeric(5,1) check (protein_100g >= 0),
  fat_100g       numeric(5,1) check (fat_100g >= 0),
  carb_100g      numeric(5,1) check (carb_100g >= 0),
  kcal_portion   numeric(6,1) not null check (kcal_portion between 0 and 5000),
  protein_portion numeric(5,1) check (protein_portion between 0 and 500),
  source         text not null check (char_length(source) between 1 and 200),
  source_ref     text check (char_length(source_ref) <= 50),
  is_custom      boolean not null default false,
  active         boolean not null default true,
  sort_order     int not null default 100,
  created_at     timestamptz not null default now()
);
alter table public.foods enable row level security;
create policy foods_select on public.foods for select using (auth.role() = 'authenticated');
create policy foods_admin on public.foods for all using (public.is_admin()) with check (public.is_admin());
grant select, insert, update, delete on public.foods to authenticated, service_role;

-- ── 每日目標（只有管理員能設） ───────────────────────────────────────────
alter table public.profiles
  add column diet_kcal_target    int check (diet_kcal_target between 800 and 6000),
  add column diet_protein_target int check (diet_protein_target between 10 and 400);
grant update (diet_kcal_target, diet_protein_target) on public.profiles to authenticated;

create or replace function public.guard_diet_target()
returns trigger language plpgsql as $$
begin
  if (new.diet_kcal_target is distinct from old.diet_kcal_target or new.diet_protein_target is distinct from old.diet_protein_target)
     and current_user = 'authenticated' and not public.is_admin() then
    raise exception 'diet targets can only be changed by admin';
  end if;
  return new;
end $$;
create trigger profiles_diet_target_guard before update on public.profiles
  for each row execute function public.guard_diet_target();

-- ── 飲食紀錄（存當下的名稱與熱量快照，食物清單之後改了也不影響舊紀錄） ─────────────
create table public.food_logs (
  id          uuid primary key default gen_random_uuid(),
  profile_id  uuid not null references public.profiles(id) on delete cascade,
  eaten_on    date not null,
  meal        text not null check (meal in ('breakfast', 'lunch', 'dinner', 'snack')),
  food_id     uuid references public.foods(id) on delete set null,
  name        text not null check (char_length(name) between 1 and 60),
  amount_label text check (char_length(amount_label) <= 40),
  kcal        numeric(6,1) not null check (kcal between 0 and 5000),
  protein_g   numeric(5,1) check (protein_g between 0 and 500),
  created_at  timestamptz not null default now()
);
create index food_logs_profile on public.food_logs (profile_id, eaten_on);
alter table public.food_logs enable row level security;
create policy food_logs_select on public.food_logs for select using (profile_id = auth.uid() or public.is_admin());
create policy food_logs_insert on public.food_logs for insert with check (
  profile_id = auth.uid() and public.is_member() and eaten_on between public.taipei_today() - 7 and public.taipei_today());
create policy food_logs_update on public.food_logs for update
  using (profile_id = auth.uid() and public.is_member())
  with check (profile_id = auth.uid() and public.is_member() and eaten_on between public.taipei_today() - 7 and public.taipei_today());
create policy food_logs_delete on public.food_logs for delete using (profile_id = auth.uid() or public.is_admin());
grant select, insert, update, delete on public.food_logs to authenticated, service_role;

